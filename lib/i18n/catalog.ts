const dictionaries: Record<Locale, Record<string, string>> = {
  en: {},
  'zh-CN': zh,
}

export function normalizeLocale(value: string | null | undefined): Locale {
  if (value === 'zh-CN' || value === 'zh') return 'zh-CN'
  return DEFAULT_LOCALE
}

export function translateExact(text: string, locale: Locale): string {
  if (locale === 'en') return text
  return dictionaries[locale][text] ?? text
}

export function translateText(text: string, locale: Locale): string {
  if (locale === 'en') return text

  const exact = translateExact(text, locale)
  if (exact !== text) return exact

  const replacements: Array<[RegExp, (...matches: string[]) => string]> = [
    [/^Last sync: (.+)$/u, value => `上次同步：${translateText(value, locale)}`],
    [/^Updated (.+)$/u, value => `更新于 ${translateText(value, locale)}`],
    [/^Error: (.+)$/u, value => `错误：${value}`],
    [/^\+(\d+) new$/u, count => `+${count} 笔新增`],
    [/^\+(\d+) new transactions$/u, count => `+${count} 笔新交易`],
    [/^(\d+) transactions$/u, count => `${count} 笔交易`],
    [/^(\d+) transaction$/u, count => `${count} 笔交易`],
    [/^(\d+) to review$/u, count => `${count} 待审核`],
    [/^(\d+) uncategorized$/u, count => `${count} 未分类`],
    [/^(\d+) review categories$/u, count => `${count} 个审核分类`],
    [/^Load more \((.+)\)$/u, value => `加载更多（${value}）`],
    [/^Total (.+)$/u, value => `合计 ${value}`],
    [/^This page has (\d+) AI suggestions to review$/u, count => `本页有 ${count} 条 AI 建议待审核`],
    [/^AI suggestion: (.+)$/u, value => `AI 建议：${value}`],
    [/^Current group: (.+)$/u, value => `当前分组：${value}`],
    [/^Categorized (\d+) transactions$/u, count => `已分类 ${count} 笔交易`],
    [/^Categorized (\d+) transactions and saved a rule$/u, count => `已分类 ${count} 笔交易并保存规则`],
    [/^(\d+) minutes ago$/u, count => `${count} 分钟前`],
    [/^(\d+) minute ago$/u, count => `${count} 分钟前`],
    [/^(\d+) hours ago$/u, count => `${count} 小时前`],
    [/^(\d+) hour ago$/u, count => `${count} 小时前`],
    [/^(\d+) days ago$/u, count => `${count} 天前`],
    [/^(\d+) day ago$/u, count => `${count} 天前`],
    [/^Range: (.+) · Basis: posted transactions, excluding cancelled$/u, range => `范围：${range} · 口径：已入账交易，不含已取消`],
  ]

  for (const [pattern, replacement] of replacements) {
    const match = text.match(pattern)
    if (match) return replacement(...match.slice(1))
  }

  if (text === 'just now') return '刚刚'
  return text
}
